// Optional tweet data is stored on each episode. Episodes without tweet show no X button.
export function storyShareUrl(event){
  const tweet=event?.tweet;
  if(typeof tweet?.text!=='string'||!tweet.text.trim())return null;
  const params=new URLSearchParams({text:tweet.text});
  if(typeof tweet.url==='string'){
    try{const url=new URL(tweet.url);if(url.protocol==='https:')params.set('url',url.href);}
    catch{/* Invalid URLs simply produce a text-only post. */}
  }
  return 'https://twitter.com/intent/tweet?'+params.toString();
}

const deliveries=state=>state.meta.history.filter(h=>!h.practice).length;
const deliveriesAfterFirstRun=state=>state.meta.history.filter(h=>!h.practice&&!String(h.attempt_id||'').startsWith('1:')).length;

export function storyPending(state){
  const r=state.run,m=state.meta.story||{};
  if(r.status!=='active')return null;
  if(r.id>1&&!(m.greetedRuns||[]).includes(r.id)){
    const variants=[
      '採用おめでとう。片桐工房へようこそ。前の担当者が残した記録を、君にも渡しておくよ。',
      '今日からよろしく頼む。この机は前任者も使っていた。残してくれた仕事の記録を役立ててくれ。',
      '採用おめでとう。前の担当者は別の仕事へ進んだ。今度は君にここの仕事を任せたい。',
      '片桐工房へようこそ。君が仕事を始められるよう、道具と記録を用意しておいた。'
    ];
    const index=(Number(state.seed.slice(-5))+r.id)%variants.length;
    return {id:'welcome-'+r.id,run:r.id,title:'採用おめでとう',pages:[
      variants[index],
      `君には通常の依頼を五件担当してもらう。開始時の信用は${'EDCBA'[r.rank-1]}だ。前任者の仕事で残った積立金から、準備金も用意してある。`,
      '工房のことは仕事の合間に話していこう。まずは今の道具と予算に合う依頼を選んでくれ。'
    ]};
  }
  const total=deliveries(state);
  if(m.lastDelivery!==undefined&&total<=m.lastDelivery)return null;
  const heard=m.heard||[],sinceRehire=deliveriesAfterFirstRun(state);
  return STORY_EPISODES.find(e=>!heard.includes(e.id)&&(e.reemployment?r.id>1&&sinceRehire>=e.after:total>=e.after))||null;
}

export function finishStory(state,event){
  const next=structuredClone(state);next.meta.story||={heard:[],greetedRuns:[]};
  const m=next.meta.story;m.heard||=[];m.greetedRuns||=[];
  const values=event.run?m.greetedRuns:m.heard,value=event.run||event.id;
  if(!values.includes(value))values.push(value);
  if(!event.run)m.lastDelivery=deliveries(state);
  return next;
}

export function promotionCall(state,event){
  if(state.run.id===1&&!(state.meta.learned_call_ids||[]).includes(event.id))return event;
  if(event.rank)return {...event,pages:[`今回の仕事も確認した。信用${'EDCBA'[Math.max(state.run.rank,event.rank)-1]}の取引先まで紹介できる。前からのKomaOSの依頼も続けて選べるので手元の道具に合う仕事を選んでくれ。`,`取引先の追加商品を用意した。仕入れの準備金$${event.grant}か解除媒体一本も選べる。前に扱った物でも今回の持ち物とOS版は確かめよう。`]};
  return event;
}
